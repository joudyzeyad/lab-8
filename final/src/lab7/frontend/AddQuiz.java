    private void saveQActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_saveQActionPerformed
        // TODO add your handling code here:
        if(content.getText().isEmpty())
            JOptionPane.showMessageDialog(this, "You must write the question content");
        else{
              String c = content.getText().trim();
              ArrayList<String> choices = new ArrayList<>();
              for(int i=0; i< model.getRowCount();++i){
                  String temp = model.getValueAt(i, 1).toString();
                  choices.add(temp);
              }
              int correct = jComboBox1.getSelectedIndex();
               Question q = new Question(c,choices,correct);
              this.quiz.addQuestion(q);
              JOptionPane.showMessageDialog(this, "Question Added Successfully");
              System.out.println("Total questions in quiz so far: " + this.quiz.getTotalQuestions());
              //reset dialagou to add another question
              content.setText("");
              model.setRowCount(0);
             model.addRow(new Object[]{"Option 1"});
             model.addRow(new Object[]{"Option 2"});
             this.updateCorrectChoice();
        }
    }//GEN-LAST:event_saveQActionPerformed

