    private void jButton2ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton2ActionPerformed
        // TODO add your handling code here:
        int selected = choicestable.getSelectedRow();
        if(selected == -1)
            JOptionPane.showMessageDialog(this, "Select the choice to remove");
        else{
              if(selected == 0 || selected == 1)
                  JOptionPane.showMessageDialog(this, "Cant delete choice 1 or 2 becuase they are default");
              else{
                  model.removeRow(selected);
                  this.updateCorrectChoice();
              }
        }
            
    }//GEN-LAST:event_jButton2ActionPerformed

